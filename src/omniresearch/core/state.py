"""State schemas and data models for OmniResearch Multi-Agent System."""

import datetime
from typing import Literal

from pydantic import BaseModel, Field


class SourceDocument(BaseModel):
    """Source reference retrieved from web or enterprise documents."""

    id: int
    title: str
    url_or_path: str
    snippet: str
    source_type: Literal["web", "pdf", "docx", "csv", "manual"] = "web"
    relevance_score: float = Field(default=1.0, ge=0.0, le=1.0)
    retrieved_at: str = Field(
        default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).isoformat()
    )


class ResearchHypothesis(BaseModel):
    """Decomposed sub-topic or hypothesis generated by Planner Agent."""

    sub_query: str
    rationale: str
    priority: int = 1
    completed: bool = False


class FactCheckClaim(BaseModel):
    """Specific quantitative or qualitative claim audited by Verifier Agent."""

    claim_text: str
    source_id: int | None = None
    source_reference: str = ""
    status: Literal["verified", "partially_verified", "unverified", "disputed"] = "unverified"
    confidence_score: float = Field(default=50.0, ge=0.0, le=100.0)
    verification_rationale: str = ""


class ReportSection(BaseModel):
    """Structured section within the Executive Dossier."""

    heading: str
    content: str
    citations: list[int] = Field(default_factory=list)


class ResearchReport(BaseModel):
    """Final executive dossier deliverable."""

    topic: str
    executive_summary: str
    sections: list[ReportSection] = Field(default_factory=list)
    key_findings: list[str] = Field(default_factory=list)
    strategic_recommendations: list[str] = Field(default_factory=list)
    fact_check_summary: list[FactCheckClaim] = Field(default_factory=list)
    sources: list[SourceDocument] = Field(default_factory=list)
    average_confidence_score: float = 0.0
    generated_at: str = Field(
        default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).strftime(
            "%Y-%m-%d %H:%M:%S UTC"
        )
    )


class ResearchState(BaseModel):
    """Shared state passed across LangGraph agent nodes."""

    topic: str
    uploaded_files: list[str] = Field(default_factory=list)
    iteration: int = 0
    max_iterations: int = 3
    plan: list[ResearchHypothesis] = Field(default_factory=list)
    sources: list[SourceDocument] = Field(default_factory=list)
    verified_claims: list[FactCheckClaim] = Field(default_factory=list)
    report: ResearchReport | None = None
    activity_log: list[str] = Field(default_factory=list)
    is_completed: bool = False
