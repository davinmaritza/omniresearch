"""Markdown Exporter for OmniResearch Executive Dossiers."""

import os

from omniresearch.core.state import ResearchReport


def format_markdown(report: ResearchReport) -> str:
    """Render a ResearchReport into an executive Markdown dossier."""
    md = []

    # Header & Badges
    md.append(f"# 📋 Executive Dossier: {report.topic}")
    md.append(f"> **Generated by OmniResearch Intelligence Engine** | {report.generated_at}")
    md.append(f"> **Empirical Confidence Rating:** `{report.average_confidence_score}%`\n")
    md.append("---\n")

    # Executive Summary
    md.append("## 🌟 1. Executive Summary\n")
    md.append(report.executive_summary)
    md.append("\n")

    # Key Findings
    if report.key_findings:
        md.append("## 🔑 2. Key Strategic Findings\n")
        for finding in report.key_findings:
            md.append(f"- **{finding}**")
        md.append("\n")

    # Structured Analytical Sections
    md.append("## 📊 3. In-Depth Analysis\n")
    for idx, sec in enumerate(report.sections, start=1):
        md.append(f"### 3.{idx}. {sec.heading}\n")
        md.append(sec.content)
        if sec.citations:
            citation_links = [f"[[Source {c}]](#source-{c})" for c in sec.citations]
            md.append(f"\n*Primary Citations: {', '.join(citation_links)}*\n")
        md.append("\n")

    # Strategic Recommendations
    if report.strategic_recommendations:
        md.append("## 🎯 4. Strategic Recommendations\n")
        for idx, rec in enumerate(report.strategic_recommendations, start=1):
            md.append(f"{idx}. {rec}")
        md.append("\n")

    # Fact-Check Audit Matrix
    if report.fact_check_summary:
        md.append("## 🛡️ 5. Empirical Fact-Check & Verification Matrix\n")
        md.append("| Claim / Asserted Metric | Status | Confidence | Ground Truth Reference |")
        md.append("| :--- | :---: | :---: | :--- |")
        for claim in report.fact_check_summary:
            status_badge = {
                "verified": "🟢 Verified",
                "partially_verified": "🟡 Partial",
                "unverified": "🔴 Unverified",
                "disputed": "❌ Disputed",
            }.get(claim.status, claim.status)

            src = f"Source {claim.source_id}" if claim.source_id else "External corroboration"
            md.append(
                f"| {claim.claim_text} | {status_badge} | `{claim.confidence_score}%` | {src} |"
            )
        md.append("\n")

    # References & Primary Sources
    if report.sources:
        md.append("## 📚 6. Primary Evidence & Cited Sources\n")
        for s in report.sources:
            src_type_badge = s.source_type.upper()
            md.append(
                f"- <a id='source-{s.id}'></a>**[Source {s.id}]** [{s.title}]({s.url_or_path}) `[{src_type_badge}]`"
            )
            if s.snippet:
                md.append(f'  > *"{s.snippet[:250]}..."*\n')
        md.append("\n")

    md.append("---\n*End of Executive Intelligence Dossier. Confidential & Proprietary.*")
    return "\n".join(md)


def export_markdown_file(report: ResearchReport, output_path: str) -> str:
    """Save formatted markdown to disk."""
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    content = format_markdown(report)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)
    return output_path
